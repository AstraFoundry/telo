// Package icons exposes the vendored Phosphor icon set (MIT, see
// svg/LICENSE), regular weight, which Telo used before the native rewrite.
// Icons are tinted with ui.Icon, which draws currentColor in the text color.
package icons

import (
	"embed"

	"github.com/egoist/mygo/ui"
)

//go:embed svg/*.svg
var files embed.FS

func load(name string) *ui.SVG {
	data, err := files.ReadFile("svg/" + name + ".svg")
	if err != nil {
		panic(err)
	}
	return ui.MustParseSVG(data)
}

