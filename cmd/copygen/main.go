// Command copygen generates the typed keys of the UI copy catalog from
// frontend/shared/copy/en.copy, so every string the interface shows lives
// in that one file and views name it by a constant the compiler checks.
//
//	go run ./cmd/copygen            # writes keys_gen.go
//	go run ./cmd/copygen -check     # fails when keys_gen.go is stale
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strings"
	"unicode"
)

var keyPattern = regexp.MustCompile(`^[a-z][A-Za-z0-9]*$`)

func main() {
	src := flag.String("src", "frontend/shared/copy/en.copy", "catalog")
	out := flag.String("out", "frontend/shared/copy/keys_gen.go", "generated keys")
	check := flag.Bool("check", false, "verify instead of writing")
	flag.Parse()
	f, err := os.Open(*src)
	if err != nil {
		fail("%v", err)
	}
	defer f.Close()
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/copygen from en.copy; DO NOT EDIT.\n\npackage copy\n\n// Keys of the catalog, in en.copy order.\nconst (\n")
	seen := map[string]int{}
	sc := bufio.NewScanner(f)
	n := 0
	for sc.Scan() {
		n++
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, text, ok := strings.Cut(line, "=")
		key, text = strings.TrimSpace(key), strings.TrimSpace(text)
		if !ok || !keyPattern.MatchString(key) || text == "" {
			fail("%s:%d: want `key = text` with a lowerCamel key", *src, n)
		}
		if prev, dup := seen[key]; dup {
			fail("%s:%d: %s repeats line %d", *src, n, key, prev)
		}
		seen[key] = n
		r := []rune(key)
		r[0] = unicode.ToUpper(r[0])
		fmt.Fprintf(&b, "\t%s Key = %q\n", string(r), key)
	}
	b.WriteString(")\n")
	code, err := format.Source(b.Bytes())
	if err != nil {
		fail("format: %v", err)
	}
	if *check {
		current, _ := os.ReadFile(*out)
		if !bytes.Equal(current, code) {
			fail("%s is stale; run `go run ./cmd/copygen`", *out)
		}
		return
	}
	if err := os.WriteFile(*out, code, 0o644); err != nil {
		fail("%v", err)
	}
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "copygen: "+format+"\n", args...)
	os.Exit(1)
}
